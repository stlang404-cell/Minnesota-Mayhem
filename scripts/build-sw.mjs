// Generates dist/sw.js: a cache-first service worker precaching every built asset (offline play).
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const dist = 'dist';
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else files.push(p); } })(dist);
const assets = files.map(f => './' + relative(dist, f).split('\\').join('/')).filter(f => f !== './sw.js');
const hash = createHash('sha1');
for (const f of files) hash.update(readFileSync(f));
const version = hash.digest('hex').slice(0, 10);
const sw = `// Auto-generated by scripts/build-sw.mjs
const CACHE = 'mm-${version}';
const ASSETS = ${JSON.stringify(['./', ...assets], null, 0)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(res => {
    if (res.ok && new URL(e.request.url).origin === location.origin) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match('./index.html'))));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${assets.length} assets precached (cache ${version})`);
